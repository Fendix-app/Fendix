// Decision D6' (round 4): what a run leaves out is decided by evidence read
// from the tree, never by a name alone; every exclusion is listed with its
// reason. These tests drive inScopeTargets, which both builds the --exclude
// patterns and the declared list, over trees that hold the evidence and trees
// that only have the names.

func minified() string { return "!function(){" + strings.Repeat("a=b(c,d);", 300) + "}();\n" }

// redteam3-d6-04: first-party code named *.min.js, or placed under vendor/,
// build/, dist/ or target/, is scanned.
func TestFirstPartyCodeWithABuildOutputNameIsScanned(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"routes.min.js":        spikeApp, // 6 ordinary lines, required by server.js
		"vendor/app/routes.js": spikeApp,
		"dist/api.js":          spikeApp,
		"build/api.js":         spikeApp,
		"target/api.js":        spikeApp,
		"node_modules/x.js":    spikeApp, // no marker, no package.json
		".venv/app.py":         picklePy,
	})
	targets := inScopeTargets(root, nil)
	if len(targets.Excludes) != 0 || targets.Coverage.Declared() {
		t.Fatalf("excluded %q / declared %q; a name is not evidence", targets.Excludes, targets.Coverage.DeclaredDetail(1<<20))
	}
	got := strings.Join(targets.files, " ")
	for _, want := range []string{"routes.min.js", "vendor/app/routes.js", "dist/api.js", "build/api.js", "target/api.js", "node_modules/x.js", ".venv/app.py"} {
		if !strings.Contains(got, want) {
			t.Errorf("%s is not a target: %s", want, got)
		}
	}
}

// sre3-03: a minified bundle is recognised by its content, whatever its name,
// and so are the libraries that cost the real-repository runs their timeouts.
func TestMinifiedAndVendoredFilesAreExcludedOnEvidenceAndListed(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"static/bundle.js":  minified(), // no "min" anywhere
		"lib/jquery.js":     vendoredJQuery(),
		"public/app.min.js": minified(),
		"src/app.js":        spikeApp,
	})
	targets := inScopeTargets(root, nil)
	if got, want := strings.Join(targets.Excludes, " "), "/lib/jquery.js /public/app.min.js /static/bundle.js"; got != want {
		t.Errorf("Excludes = %q, want %q", got, want)
	}
	if got := strings.Join(targets.files, " "); got != "src/app.js" {
		t.Errorf("targets = %q; want only src/app.js", got)
	}
	const want = "declared out of scope, not scanned: vendored library 1 (lib/jquery.js), minified 2 (public/app.min.js, static/bundle.js)"
	if got := targets.Coverage.DeclaredDetail(240); got != want {
		t.Errorf("declared = %q, want %q", got, want)
	}
}

// An over-cap file is a gap unless there is evidence; a lockfile NAME is not.
func TestOverCapFilesAreDeclaredOnlyWithEvidence(t *testing.T) {
	root := t.TempDir()
	huge := func(prefix string) string { return prefix + strings.Repeat("a", scope.MaxFileBytes) + "\n" }
	writeTree(t, root, map[string]string{
		"api/user.pb.go":        "// Code generated by protoc-gen-go. DO NOT EDIT.\n" + huge("package api\n// "),
		"web/bundle.js":         strings.Repeat("!function(){"+strings.Repeat("a=b(c,d);", 300)+"}();\n", 400),
		"src/big.js":            huge("// "), // ordinary, over the cap: a gap
		"package-lock.json":     "{}",        // under the cap: not a Semgrep target at all
		"web/gen/data.py":       huge("# "),  // no header
		"web/gen/gen_data.py":   "# This file is automatically generated. Do not edit.\n" + huge("# "),
		"web/gen/fake-lock.js":  huge("// package-lock.json\n// "),
		"web/gen/yarn.lock.min": "x",
	})
	targets := inScopeTargets(root, nil)
	lost := targets.Coverage.LostDetail(1 << 20)
	if n := targets.Coverage.LostFiles(); n != 3 {
		t.Errorf("LostFiles = %d (%s); want the three over-cap files with no evidence", n, lost)
	}
	for _, f := range []string{"src/big.js", "web/gen/data.py", "web/gen/fake-lock.js"} {
		if !strings.Contains(lost, f) {
			t.Errorf("%s with no evidence is not listed lost: %q", f, lost)
		}
	}
	declared := targets.Coverage.DeclaredDetail(1 << 20)
	for _, want := range []string{"generator header 2 (api/user.pb.go, web/gen/gen_data.py)", "minified 1 (web/bundle.js)"} {
		if !strings.Contains(declared, want) {
			t.Errorf("declared %q lacks %q", declared, want)
		}
	}
	// Over-cap evidence-bearing files are not handed to Semgrep as excludes:
	// Semgrep skips an over-cap file by itself.
	if len(targets.Excludes) != 0 {
		t.Errorf("Excludes = %q; Semgrep's own size cap leaves them out", targets.Excludes)
	}
}

// excludePattern: a pattern that names exactly one path, escaped; a path that
// cannot be written safely is not excluded and stays in scope.
func TestExcludePatternsAreAnchoredAndEscaped(t *testing.T) {
	for _, tc := range []struct {
		rel  string
		want string
		ok   bool
	}{
		{"vendor", "/vendor", true},
		{"web/lib/jquery.js", "/web/lib/jquery.js", true},
		{"a b/c.js", "/a b/c.js", true},
		{"br[x]/w.js", `/br\[x\]/w.js`, true},
		{"a*b?.js", `/a\*b\?.js`, true},
		{"back\\slash.js", `/back\\slash.js`, true},
		{"!bang.js", "/!bang.js", true},
		{"#hash.js", "/#hash.js", true},
		{"héllo/ü.js", "/héllo/ü.js", true},
		{"line\nbreak.js", "", false},
		{"nul\x00.js", "", false},
		{" lead.js", "", false},
		{"trail.js ", "", false},
		{"bad\xffutf.js", "", false},
		{"", "", false},
	} {
		got, ok := excludePattern(tc.rel)
		if got != tc.want || ok != tc.ok {
			t.Errorf("excludePattern(%q) = %q, %v; want %q, %v", tc.rel, got, ok, tc.want, tc.ok)
		}
	}
}

func TestAPathThatCannotBeExcludedStaysInScope(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"web/new\nline.js": minified(), "web/plain.js": minified(), "ok.js": spikeApp})
	targets := inScopeTargets(root, nil)
	files := strings.Join(targets.files, "|")
	if !strings.Contains(files, "web/new\nline.js") {
		t.Errorf("a minified file whose name cannot be written as a pattern was dropped: %q", files)
	}
	if got := strings.Join(targets.Excludes, " "); got != "/web/plain.js" {
		t.Errorf("Excludes = %q; only the file that can be named is excluded", got)
	}
	if targets.Coverage.DeclaredFiles() != 1 {
		t.Errorf("declared %d; the one excluded", targets.Coverage.DeclaredFiles())
	}
}

func TestTheExcludeCountIsBounded(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{}
	for i := 0; i < maxExcludes+5; i++ {
		files["b/"+strings.Repeat("x", 3)+string(rune('a'+i%26))+strings.Repeat("y", i/26)+".js"] = minified()
	}
	writeTree(t, root, files)
	targets := inScopeTargets(root, nil)
	if len(targets.Excludes) != maxExcludes {
		t.Errorf("Excludes = %d, want the bound %d", len(targets.Excludes), maxExcludes)
	}
	if got := targets.Coverage.DeclaredFiles(); got != maxExcludes {
		t.Errorf("declared %d; only what Semgrep is told to skip is declared", got)
	}
	if len(targets.files) != 5 {
		t.Errorf("%d files past the bound stay in scope, want 5", len(targets.files))
	}
}

// redteam3-d6-01: a changed file under an installed or built tree is listed in
// a diff scan, as it is in a full one, and the tree is excluded.
func TestDiffScanListsAChangedFileUnderAnInstalledTree(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"node_modules/.package-lock.json": `{"lockfileVersion": 3}`,
		"node_modules/lib/i.js":           spikeApp,
		"node_modules/lib/j.js":           spikeApp,
		"vendor/app.js":                   spikeApp, // no marker: a changed first-party file
		"src/a.js":                        spikeApp,
	})
	allow := gitdiff.NewAllowlist(root, []string{"node_modules/lib/i.js", "node_modules/lib/j.js", "vendor/app.js", "src/a.js"})
	targets := inScopeTargets(root, allow)
	if got := strings.Join(targets.files, " "); got != "src/a.js vendor/app.js" {
		t.Errorf("targets = %q", got)
	}
	if got, want := targets.Coverage.DeclaredDetail(240), "declared out of scope, not scanned: installed npm packages 1 (node_modules/)"; got != want {
		t.Errorf("declared = %q, want %q", got, want)
	}
	if got := strings.Join(targets.Excludes, " "); got != "/node_modules" {
		t.Errorf("Excludes = %q", got)
	}
}

func TestDiffScanListsAChangedFileReachedThroughALink(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	writeTree(t, outside, map[string]string{"x.js": spikeApp})
	writeTree(t, root, map[string]string{"src/a.js": spikeApp})
	if err := os.Symlink(outside, filepath.Join(root, "linked")); err != nil {
		t.Skip("no symlinks here")
	}
	allow := gitdiff.NewAllowlist(root, []string{"linked/x.js", "src/a.js"})
	targets := inScopeTargets(root, allow)
	if got := targets.Coverage.Names(scope.ReasonSymlink); len(got) != 1 || got[0] != "linked/x.js" {
		t.Errorf("symlink names = %q; want linked/x.js", got)
	}
	if got := strings.Join(targets.files, " "); got != "src/a.js" {
		t.Errorf("targets = %q", got)
	}
}

// sre3-06 (Semgrep's half): a symbolic link to source, or to a directory, is
// listed as not followed, never silently skipped.
func TestSymlinksAreListedNotFollowed(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	writeTree(t, outside, map[string]string{"real.py": picklePy, "dir/x.js": spikeApp})
	writeTree(t, root, map[string]string{"app.py": picklePy, "notes.txt": "x"})
	for name, target := range map[string]string{"helper.py": filepath.Join(outside, "real.py"), "shared": filepath.Join(outside, "dir"), "readme-link.txt": filepath.Join(root, "notes.txt")} {
		if err := os.Symlink(target, filepath.Join(root, name)); err != nil {
			t.Skip("no symlinks here")
		}
	}
	targets := inScopeTargets(root, nil)
	got := targets.Coverage.Names(scope.ReasonSymlink)
	if strings.Join(got, " ") != "helper.py shared/" {
		t.Errorf("symlinks = %q; want helper.py and shared/ (a link to a text file is not source)", got)
	}
	if targets.Coverage.Lost() {
		t.Errorf("a link is declared, not lost: %s", targets.Coverage.LostDetail(240))
	}
}

// redteam3-semgrep-02, redteam4-d6-02, DE4-04: a source file Semgrep does not
// select by its extension (another case, or .cts/.mts/.es6/.vue) is in scope,
// never declared out of scope by its name. It is handed to Semgrep by name (the
// extensions pass); a file the pass does not report is lost evaluation.
func TestFilesSemgrepDoesNotSelectAreInScopeAndGoToTheExtensionsPass(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"APP.JS": spikeApp, "Server.Py": picklePy, "x.cts": spikeApp, "ui.vue": "<template/>", "a.js": spikeApp, "notes.TXT": "x"})
	targets := inScopeTargets(root, nil)
	if got := strings.Join(targets.files, " "); got != "APP.JS Server.Py a.js ui.vue x.cts" {
		t.Errorf("targets = %q; want every source file, whatever the case of its extension", got)
	}
	if got := strings.Join(targets.explicit, " "); got != "APP.JS Server.Py ui.vue x.cts" {
		t.Errorf("explicit = %q; want the files Semgrep does not select itself", got)
	}
	if targets.Coverage.DeclaredCount(scope.ReasonNotChosen) != 0 {
		t.Errorf("a file name must not declare source out of scope: %v", targets.Coverage.Names(scope.ReasonNotChosen))
	}
	if languageOf("APP.JS") != "javascript" || languageOf("app.js") != "javascript" || languageOf("a.PYI") != "python" || languageOf("n.TXT") != "" {
		t.Error("languageOf must match the extension without regard to case")
	}
	if semgrepSelects("APP.JS") || !semgrepSelects("app.js") {
		t.Error("semgrepSelects must match the extension exactly, as Semgrep does")
	}
	// Unreported by Semgrep, they are lost evaluation, named.
	targets.checkScanned(map[string]bool{"a.js": true}, true)
	if got := targets.Coverage.LostDetail(240); !strings.Contains(got, "APP.JS") || !strings.Contains(got, "Server.Py") {
		t.Errorf("lost = %q; want the unreported upper-case files named", got)
	}
}

// qa3-02: an unreadable directory under the walk is listed unreadable.
func TestAnUnreadableDirectoryIsListed(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("root reads every directory")
	}
	root := t.TempDir()
	writeTree(t, root, map[string]string{"ok/a.js": spikeApp, "secret/b.js": spikeApp})
	if err := os.Chmod(filepath.Join(root, "secret"), 0); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(filepath.Join(root, "secret"), 0o755) })
	targets := inScopeTargets(root, nil)
	if got := targets.Coverage.LostDetail(240); got != "lost evaluation: 1 in-scope file not read: 1 unreadable (secret/)" {
		t.Errorf("lost = %q", got)
	}
}

// qa3-02: every spelling of a rule error is a rule error, so a pack that did
// not load is never read as a pack that found nothing.
func TestEveryRuleErrorSpellingIsARuleError(t *testing.T) {
	for typ := range ruleErrorTypes {
		doc := `{"results":[],"errors":[{"level":"error","type":"` + typ + `","message":"bad rule","path":"/x/r.yaml"}],"time":{"fixpoint_timeouts":[]}}`
		run := parseRun([]byte(doc), t.TempDir())
		if len(run.RuleErrors) != 1 || run.RuleErrors[0].Type != typ {
			t.Errorf("%q: RuleErrors = %+v", typ, run.RuleErrors)
		}
	}
	for _, typ := range []string{"Rule parse error", "Invalid YAML", "Pattern parse error", "Incompatible rule", "InvalidRuleSchemaError", "RuleParseError", "PatternParseError", "UnknownLanguageError", "InvalidYaml", "IncompatibleRule"} {
		if !ruleErrorTypes[typ] {
			t.Errorf("%q is not a rule error type", typ)
		}
	}
}
