// TestScanOffline_PoetryLockTransitiveVuln proves the headline value of
// item 3: a vulnerability in a TRANSITIVE dependency — one that does not
// appear in requirements.txt but is pinned in poetry.lock — is surfaced.
// This is the "locks ARE the transitive closure" win that kills the
// "PyPI direct-deps only" limitation.
func TestScanOffline_PoetryLockTransitiveVuln(t *testing.T) {
	dir := t.TempDir()
	// A project whose direct dep is flask, but whose lockfile pins a
	// vulnerable transitive jinja2. requirements.txt would miss jinja2.
	lock := `# generated by poetry
[[package]]
name = "flask"
version = "2.3.0"

[package.dependencies]
jinja2 = ">=3.0"

[[package]]
name = "jinja2"
version = "3.0.0"
`
	if err := os.WriteFile(filepath.Join(dir, "poetry.lock"), []byte(lock), 0o644); err != nil {
		t.Fatal(err)
	}

	snap := offline.FromOSVExport([]offline.Advisory{
		{
			ID:      "GHSA-jinja2-xss",
			Aliases: []string{"CVE-2026-2222"},
			Package: offline.PackageRef{Ecosystem: "PyPI", Name: "jinja2"},
			Ranges:  []offline.Range{{Introduced: "0.0.0", Fixed: "3.1.3"}},
			Summary: "Jinja2 XSS via template",
		},
	}, []string{"osv.dev"})

	findings, err := ScanOffline(dir, DefaultRecurseDepth, snap)
	if err != nil {
		t.Fatalf("ScanOffline: %v", err)
	}
	if len(findings) != 1 {
		t.Fatalf("expected 1 finding (transitive jinja2), got %d: %+v", len(findings), findings)
	}
	f := findings[0]
	// FIX-05 canonical id: the advisory's CVE alias wins over the GHSA id.
	if f.ID != "SEC-DEPS-CVE_2026_2222" {
		t.Errorf("ID = %q; want SEC-DEPS-CVE_2026_2222", f.ID)
	}
	// The finding must attribute the poetry.lock manifest, not requirements.txt.
	if f.Endpoint != "poetry.lock" {
		t.Errorf("Endpoint = %q; want poetry.lock", f.Endpoint)
	}
}

// TestScanOffline_PipfileLockVuln proves the same for Pipfile.lock (pipenv).
func TestScanOffline_PipfileLockVuln(t *testing.T) {
	dir := t.TempDir()
	lock := `{
  "default": {
    "django": {"version": "==4.0.0"}
  },
  "develop": {}
}`
	if err := os.WriteFile(filepath.Join(dir, "Pipfile.lock"), []byte(lock), 0o644); err != nil {
		t.Fatal(err)
	}
	snap := offline.FromOSVExport([]offline.Advisory{{
		ID:      "GHSA-django-sqli",
		Package: offline.PackageRef{Ecosystem: "PyPI", Name: "django"},
		Ranges:  []offline.Range{{Introduced: "0.0.0", Fixed: "4.0.6"}},
		Summary: "Django SQLi",
	}}, []string{"osv.dev"})

	findings, err := ScanOffline(dir, DefaultRecurseDepth, snap)
	if err != nil {
		t.Fatalf("ScanOffline: %v", err)
	}
	if len(findings) != 1 || findings[0].Endpoint != "Pipfile.lock" {
		t.Fatalf("expected 1 Pipfile.lock finding, got %+v", findings)
	}
}

// TestScanOffline_MixedManifests proves a repo with BOTH requirements.txt
// and poetry.lock scans both and attributes each finding to its source.
func TestScanOffline_MixedManifests(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "requirements.txt"), []byte("flask==2.0.0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	sub := filepath.Join(dir, "svc")
	if err := os.MkdirAll(sub, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(sub, "poetry.lock"),
		[]byte("[[package]]\nname = \"requests\"\nversion = \"2.0.0\"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	snap := offline.FromOSVExport([]offline.Advisory{
		{ID: "GHSA-flask", Package: offline.PackageRef{Ecosystem: "PyPI", Name: "flask"},
			Ranges: []offline.Range{{Introduced: "0.0.0", Fixed: "9.9.9"}}},
		{ID: "GHSA-requests", Package: offline.PackageRef{Ecosystem: "PyPI", Name: "requests"},
			Ranges: []offline.Range{{Introduced: "0.0.0", Fixed: "9.9.9"}}},
	}, []string{"osv.dev"})

	findings, err := ScanOffline(dir, DefaultRecurseDepth, snap)
	if err != nil {
		t.Fatalf("ScanOffline: %v", err)
	}
	if len(findings) != 2 {
		t.Fatalf("expected 2 findings across both manifests, got %d: %+v", len(findings), findings)
	}
	endpoints := map[string]bool{}
	for _, f := range findings {
		endpoints[f.Endpoint] = true
	}
	if !endpoints["requirements.txt"] || !endpoints[filepath.Join("svc", "poetry.lock")] {
		t.Errorf("findings not attributed to both manifests: %v", endpoints)
	}
}
