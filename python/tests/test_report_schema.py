"""Every report the engine writes must validate against docs/schema.json.

Round 6, WS-E2: R5-08 (RC-4, gate G2.4). ``docs/schema.json`` sets
``additionalProperties: false`` throughout, so a key the engine writes and the
schema does not list makes the engine's own report invalid for any consumer who
checks. That happened: ``ImportedTool`` lacked ``execution_successful``,
``error_notifications`` and ``analyzed_paths``, and jsonschema rejected every
import report that recorded its producer's run. The Go drift test
(go/internal/reporters/schema_drift_test.go) walks the structs; this validates
real documents with a real JSON Schema validator.

Positive fixtures (tests/fixtures/report_schema/):
  engine/  the engine's own import reports, regenerated by
           ``UPDATE_GOLDEN=1 go test ./internal/engine -run TestRunImport_R6_ReportGoldens``;
  corpus/  reports written by the HEAD engine on local targets (a whitebox
           scan, and an active scan of a target that answers 403 to almost
           everything: the R5-07 shape);
  v370/    real v3.7.0 reports (the backend's cls5 fixtures, plus an
           import-mode report from the v3.7.0 image): the schema must keep
           accepting what it claims to accept.
Negative fixtures are mutations of a positive one and must be rejected.
"""

import copy
import json
from pathlib import Path

import pytest
from jsonschema import Draft7Validator

REPO = Path(__file__).resolve().parents[2]
SCHEMA_PATH = REPO / "docs" / "schema.json"
FIXTURES = Path(__file__).resolve().parent / "fixtures" / "report_schema"
ENGINE = sorted((FIXTURES / "engine").glob("*.json"))
CORPUS = sorted((FIXTURES / "corpus").glob("*.json"))
V370 = sorted((FIXTURES / "v370").glob("*.json"))


@pytest.fixture(scope="module")
def validator():
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    Draft7Validator.check_schema(schema)
    return Draft7Validator(schema)


def _load(path):
    return json.loads(path.read_text(encoding="utf-8"))


def _errors(validator, doc):
    return sorted(f"{'/'.join(str(p) for p in e.absolute_path)}: {e.message}" for e in validator.iter_errors(doc))


def test_fixture_sets_are_present():
    assert len(ENGINE) >= 5, ENGINE
    assert len(CORPUS) >= 2, CORPUS
    assert len(V370) >= 5, V370


@pytest.mark.parametrize("path", ENGINE + CORPUS, ids=lambda p: f"{p.parent.name}/{p.name}")
def test_engine_report_validates(validator, path):
    assert _errors(validator, _load(path)) == []


@pytest.mark.parametrize("path", V370, ids=lambda p: p.name)
def test_v370_report_still_validates(validator, path):
    assert _errors(validator, _load(path)) == []


def _import_report_with_record():
    """An import report whose tool block carries the producer's run record."""
    doc = _load(FIXTURES / "engine" / "import_failed.json")
    tool = doc["metadata"]["imports"][0]
    assert "execution_successful" in tool, "fixture error: no run record in the import golden"
    return doc


def test_error_notifications_zero_is_valid(validator):
    doc = _import_report_with_record()
    doc["metadata"]["imports"][0]["error_notifications"] = 0
    assert _errors(validator, doc) == []


# Each mutation must be rejected: proves additionalProperties and the types
# still bite after the schema gains the run-record keys.
NEGATIVES = {
    "unknown key in ImportedTool": lambda d: d["metadata"]["imports"][0].__setitem__("rules_failed", 1),
    "error_notifications -1": lambda d: d["metadata"]["imports"][0].__setitem__("error_notifications", -1),
    "error_notifications a string": lambda d: d["metadata"]["imports"][0].__setitem__("error_notifications", "1"),
    "execution_successful a string": lambda d: d["metadata"]["imports"][0].__setitem__("execution_successful", "false"),
    "analyzed_paths not strings": lambda d: d["metadata"]["imports"][0].__setitem__("analyzed_paths", [1]),
    "results -1": lambda d: d["metadata"]["imports"][0].__setitem__("results", -1),
    "unknown key at the report root": lambda d: d.__setitem__("extra", True),
    "unknown key in metadata": lambda d: d["metadata"].__setitem__("extra", True),
    "unknown key in coverage": lambda d: d["metadata"]["coverage"].__setitem__("extra", True),
}


@pytest.mark.parametrize("name", sorted(NEGATIVES))
def test_negative_import_report_is_rejected(validator, name):
    doc = copy.deepcopy(_load(FIXTURES / "v370" / "v370-import-failed.json"))
    # Built on a v3.7.0 document so the negatives are judged today, before the
    # schema lists the run-record keys: each mutation is the only defect.
    NEGATIVES[name](doc)
    assert _errors(validator, doc) != [], f"{name} was accepted"


def _active_report():
    doc = _load(FIXTURES / "v370" / "v370-p-503.json")
    assert doc["metadata"].get("coverage"), "fixture error"
    return doc


def _with_active_probes(doc, ap):
    doc = copy.deepcopy(doc)
    doc["metadata"]["coverage"]["active_probes"] = ap
    return doc


BASE_AP = {
    "attempted": 10,
    "evaluated": 8,
    "inconclusive": 2,
    "unknown_origin": 0,
    "scanner_failed": 0,
    "reasons": {"target": {"gated": 2}},
    "not_evaluated_checks": [],
    "truncated": False,
    "gated": {"total": 2, "by_status": {"403": 2}},
}


@pytest.mark.parametrize(
    "field,value",
    [("attempted", -1), ("evaluated", -1), ("inconclusive", -1), ("unknown_origin", -1), ("scanner_failed", -1)],
)
def test_negative_probe_count_is_rejected(validator, field, value):
    ap = dict(BASE_AP, **{field: value})
    assert _errors(validator, _with_active_probes(_active_report(), ap)) != []


def test_zero_probe_counts_are_valid(validator):
    ap = dict(BASE_AP, attempted=0, evaluated=0, inconclusive=0, reasons={}, gated={"total": 0, "by_status": {}})
    assert _errors(validator, _with_active_probes(_active_report(), ap)) == []


# A-D5 engine half (PHASE1-GATE-PROPOSALS 1.4b): the bounded evidence keys the
# engine adds to active_probes. Names are the proposal shared with WS-B1.
D5_AP = dict(
    BASE_AP,
    not_evaluated_counts=[{"origin": "target", "reason": "gated", "status": 403, "count": 2}],
    not_evaluated_groups=[
        {"endpoint": "GET /api/r01", "origin": "target", "reason": "gated", "checks": ["injection"]},
        {"endpoint": "GET /api/r02", "origin": "target", "reason": "gated", "checks": ["injection"]},
    ],
    groups_total=2,
    inline_truncated=False,
    listing_ceiling_reached=False,
    listing_overflow=0,
)


def test_d5_bounded_evidence_keys_validate(validator):
    assert _errors(validator, _with_active_probes(_active_report(), D5_AP)) == []


@pytest.mark.parametrize(
    "mutate",
    [
        lambda ap: ap.__setitem__("groups_total", -1),
        lambda ap: ap.__setitem__("listing_overflow", -1),
        lambda ap: ap.__setitem__("inline_truncated", "no"),
        lambda ap: ap["not_evaluated_counts"][0].__setitem__("count", 0),
        lambda ap: ap["not_evaluated_counts"][0].__setitem__("extra", 1),
        lambda ap: ap["not_evaluated_groups"][0].__setitem__("extra", 1),
    ],
    ids=["groups_total -1", "listing_overflow -1", "inline_truncated string", "count 0", "unknown key in a count row", "unknown key in a group"],
)
def test_d5_bounded_evidence_negatives_are_rejected(validator, mutate):
    ap = copy.deepcopy(D5_AP)
    mutate(ap)
    assert _errors(validator, _with_active_probes(_active_report(), ap)) != []
